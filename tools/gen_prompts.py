"""
Generate `crates/tg-caption/src/prompt_templates.rs` from the Python app's
`prompt_templates.py` - the Python file is the source of truth; the Rust
side is generated so the two can never drift.

Usage:
    python tools/gen_prompts.py <path-to-taggui>
"""
import sys
from pathlib import Path


def rust_str(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    taggui_root = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(taggui_root / 'taggui'))

    from auto_captioning.prompt_templates import (
        CAPTIONER_PROMPT_SUFFIXES, PROMPT_TEMPLATES, PROMPT_TEMPLATE_CAPTIONERS,
        PROMPT_TEMPLATE_PURPOSES)

    out = []
    out.append('//! GENERATED by `tools/gen_prompts.py` from the Python')
    out.append('//! app\'s `prompt_templates.py` - do not edit by hand;')
    out.append('//! regenerate instead. The Python file is the source of')
    out.append('//! truth for template wording and rationale.')
    out.append('')
    out.append('use std::collections::HashMap;')
    out.append('')
    out.append('/// `PROMPT_TEMPLATE_PURPOSES`')
    out.append(
        'pub const PURPOSES: [&str; %d] = %s;' % (
            len(PROMPT_TEMPLATE_PURPOSES),
            '[' + ', '.join(rust_str(p) for p in PROMPT_TEMPLATE_PURPOSES)
            + ']'))
    out.append('')
    out.append('/// `PROMPT_TEMPLATE_CAPTIONERS`')
    out.append(
        'pub const CAPTIONERS: [&str; %d] = %s;' % (
            len(PROMPT_TEMPLATE_CAPTIONERS),
            '[' + ', '.join(rust_str(c) for c in PROMPT_TEMPLATE_CAPTIONERS)
            + ']'))
    out.append('')
    out.append('/// `CAPTIONER_PROMPT_SUFFIXES`, keyed by captioner name')
    out.append('/// (empty string for "(none)").')
    out.append('pub fn captioner_suffix(captioner: &str) -> Option<&\'static str> {')
    entries = []
    for name, suffix in CAPTIONER_PROMPT_SUFFIXES.items():
        entries.append('        %s => Some(%s),' % (rust_str(name),
                                                    rust_str(suffix)))
    out.append('    match captioner {')
    out.extend(entries)
    out.append('        _ => None,')
    out.append('    }')
    out.append('}')
    out.append('')
    out.append('/// `PROMPT_TEMPLATES`: target image-generation model ->')
    out.append('/// purpose -> prompt text.')
    out.append('pub fn prompt_template(model: &str, purpose: &str)')
    out.append("    -> Option<&'static str>")
    out.append('{')
    out.append('    static TEMPLATES: std::sync::OnceLock<')
    out.append('        HashMap<&\'static str, HashMap<&\'static str,')
    out.append("        &'static str>>> = std::sync::OnceLock::new();")
    out.append('    let templates = TEMPLATES.get_or_init(|| {')
    out.append('        let mut templates = HashMap::new();')
    for model_name, purposes in PROMPT_TEMPLATES.items():
        slug = ''.join(
            character if character.isalnum() else '_'
            for character in model_name.lower())
        out.append('        let mut %s = HashMap::new();' % slug)
        for purpose, text in purposes.items():
            out.append('        %s.insert(%s, %s);' % (
                slug, rust_str(purpose), rust_str(text)))
        out.append('        templates.insert(%s, %s);' % (
            rust_str(model_name), slug))
    out.append('        templates')
    out.append('    });')
    out.append('    templates.get(model).and_then(|purposes| {')
    out.append('        purposes.get(purpose).copied()')
    out.append('    })')
    out.append('}')
    out.append('')

    out_path = (Path(__file__).resolve().parent.parent / 'crates'
                / 'tg-caption' / 'src' / 'prompt_templates.rs')
    out_path.write_text('\n'.join(out), encoding='utf-8')
    print(f'Wrote {out_path}')


if __name__ == '__main__':
    main()
